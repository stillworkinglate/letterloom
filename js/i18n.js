  let language = 'en';

  function interpolate(template, vars) {
    if (!vars) return template;
    return String(template).replace(/\{(\w+)\}/g, (_, key) =>
      vars[key] == null ? '' : String(vars[key])
    );
  }

  function pluralS(n) {
    return Number(n) === 1 ? '' : 's';
  }

  function t(key, vars) {
    const catalog = CATALOGS[language] || EN;
    const template = catalog[key] != null ? catalog[key] : EN[key] != null ? EN[key] : key;
    const merged = Object.assign({ s: pluralS(vars && vars.n) }, vars);
    return interpolate(template, merged);
  }

  function normalizeLanguage(value) {
    return String(value || '').toLowerCase() === 'es' ? 'es' : 'en';
  }

  function readStoredLanguage() {
    try {
      if (typeof localStorage === 'undefined') return null;
      return localStorage.getItem(STORAGE_KEY);
    } catch (err) {
      return null;
    }
  }

  function setLanguage(next) {
    language = normalizeLanguage(next);
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(STORAGE_KEY, language);
      }
    } catch (err) {
      /* ignore quota / private mode */
    }
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = language === 'es' ? 'es' : 'en';
      document.documentElement.setAttribute('translate', 'no');
    }
    return language;
  }

  function getLanguage() {
    return language;
  }

  function init() {
    setLanguage(readStoredLanguage() || 'en');
  }

  function translateEngineError(message) {
    if (!message) return '';
    const exact = ENGINE_EXACT[message];
    if (exact) return t(exact);
    let match = String(message).match(/^Invalid word\(s\): (.+)$/);
    if (match) return t('errInvalidWords', { words: match[1] });
    match = String(message).match(/^Tile id (.+) is not on the current player's rack\.$/);
    if (match) return t('errTileNotOnRack', { id: match[1] });
    match = String(message).match(
      /^Cannot exchange when fewer than (\d+) tiles remain in the bag\.$/
    );
    if (match) return t('errExchangeBag', { n: match[1] });
    return message;
  }

  const LetterloomI18n = {
    t,
    setLanguage,
    getLanguage,
    normalizeLanguage,
    init,
    translateEngineError,
    STORAGE_KEY,
  };

  global.LetterloomI18n = LetterloomI18n;
  init();
